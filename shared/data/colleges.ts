export function getAdmissionChance(college: College, studentGpa: number, studentSat: number | null, studentAct: number | null): 'Likely / Safety' | 'Target' | 'Reach' | 'High Reach' {
  // If college acceptance rate is below 12%, it is inherently a Reach or High Reach
  if (college.acceptanceRate < 0.12) {
    return 'Reach';
  }

  let gpaScore = 0; // -1 below, 0 target, 1 above
  if (studentGpa >= college.avgGpa + 0.1) gpaScore = 1;
  else if (studentGpa >= college.avgGpa - 0.15) gpaScore = 0;
  else gpaScore = -1;

  let testScore = 0;
  if (studentSat) {
    if (studentSat >= college.sat75th) testScore = 1;
    else if (studentSat >= college.sat25th) testScore = 0;
    else testScore = -1;
  } else if (studentAct) {
    if (studentAct >= college.act75th) testScore = 1;
    else if (studentAct >= college.act25th) testScore = 0;
    else testScore = -1;
  }

  const composite = gpaScore + testScore;

  if (composite >= 1 && college.acceptanceRate > 0.35) {
    return 'Likely / Safety';
  } else if (composite >= 0 && college.acceptanceRate >= 0.20) {
    return 'Target';
  } else {
    return 'Reach';
  }
}
